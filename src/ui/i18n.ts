export type StringKey = keyof typeof STRINGS_RAW.sk;
export const STRINGS: Record<Lang, Partial<Record<StringKey, string>>> = STRINGS_RAW;

export const ORDER: Lang[] = ["sk", "cs", "pl", "hu", "de", "en", "fr", "it", "es", "pt", "nl", "uk"];

/** First browser language that has a translation, else English. */
export function detect(): Lang {
  const prefs = (navigator.languages && navigator.languages.length
    ? navigator.languages : [navigator.language || "en"]).map((l) => l.toLowerCase().slice(0, 2));
  return (prefs.find((l) => l in STRINGS) as Lang | undefined) || "en";
}

export const isLang = (v: unknown): v is Lang => typeof v === "string" && v in STRINGS;
